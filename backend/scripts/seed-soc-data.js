import { PrismaClient } from '@prisma/client';
import crypto from 'crypto';

const prisma = new PrismaClient();

const THREAT_SOURCES = ["WAF", "Endpoint", "IDS/IPS", "Cloud", "Application", "Firewall"];
const EVENT_TYPES = [
  "SQL Injection Attempt", 
  "Brute Force Login", 
  "XSS Attempt", 
  "Malware Detected", 
  "Suspicious Login", 
  "Port Scan Detected", 
  "Data Exfiltration Attempt", 
  "Phishing Attempt Blocked"
];
const SEVERITIES = ["INFO", "WARN", "CRITICAL"];
const COUNTRIES = ["US", "IN", "RU", "CN", "DE", "SG", "BR", "FR"];

function getRandomItem(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

function getRandomDate(daysBack) {
  const date = new Date();
  date.setDate(date.getDate() - Math.floor(Math.random() * daysBack));
  date.setHours(Math.floor(Math.random() * 24));
  date.setMinutes(Math.floor(Math.random() * 60));
  return date;
}

function getRandomIP() {
  return `${Math.floor(Math.random() * 255)}.${Math.floor(Math.random() * 255)}.${Math.floor(Math.random() * 255)}.${Math.floor(Math.random() * 255)}`;
}

async function seed() {
  console.log("Seeding SOC data...");

  let adminUser = await prisma.user.findFirst({
    where: { role: { in: ['SUPER_ADMIN', 'SECURITY_ADMIN', 'ADMIN'] } }
  });

  if (!adminUser) {
    adminUser = await prisma.user.create({
      data: {
        email: "soc_admin@example.com",
        name: "SOC Admin",
        role: "SECURITY_ADMIN",
      }
    });
  }

  // 1. Seed ThreatEvents
  const threatEvents = [];
  for (let i = 0; i < 500; i++) {
    threatEvents.push({
      ip: getRandomIP(),
      eventType: getRandomItem(EVENT_TYPES),
      points: Math.floor(Math.random() * 100),
      severity: getRandomItem(SEVERITIES),
      details: {
        source: getRandomItem(THREAT_SOURCES),
        country: getRandomItem(COUNTRIES),
        userAgent: "Mozilla/5.0",
        path: "/api/login",
      },
      createdAt: getRandomDate(30),
    });
  }
  await prisma.threatEvent.createMany({ data: threatEvents });
  console.log("Created 500 ThreatEvents.");

  // 2. Seed AuditLogs
  const auditActions = ["USER_LOGIN", "UPDATE_POLICY", "EXPORT_DATA", "DELETE_USER", "FAILED_LOGIN"];
  const auditLogs = [];
  for (let i = 0; i < 300; i++) {
    auditLogs.push({
      actorId: adminUser.id,
      action: getRandomItem(auditActions),
      targetType: "System",
      targetId: crypto.randomUUID(),
      details: { reason: "Routine check" },
      ip: getRandomIP(),
      userAgent: "Chrome/91.0",
      createdAt: getRandomDate(30),
    });
  }
  await prisma.auditLog.createMany({ data: auditLogs });
  console.log("Created 300 AuditLogs.");

  // 3. Seed Incidents
  const incidentStatuses = ["OPEN", "IN_PROGRESS", "RESOLVED", "CLOSED"];
  const incidentSeverities = ["INFO", "LOW", "MEDIUM", "HIGH", "CRITICAL"];
  const incidents = [];
  for (let i = 0; i < 50; i++) {
    incidents.push({
      title: getRandomItem(EVENT_TYPES),
      description: "Automated alert generated by SIEM.",
      severity: getRandomItem(incidentSeverities),
      status: getRandomItem(incidentStatuses),
      createdById: adminUser.id,
      createdAt: getRandomDate(14),
      updatedAt: new Date(),
    });
  }
  await prisma.incident.createMany({ data: incidents });
  console.log("Created 50 Incidents.");

  console.log("SOC Seeding Complete!");
}

seed()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
